#!/bin/sh
# Full-source Kotlin type-check of the app (all of app/src/main/java)
# against android.jar + the real dependency jars — the local
# substitute for `gradle :app:assembleDebug` used during the money
# build, whose Gradle daemon cannot stay alive in the build sandbox
# (daemon starts; the client loses communication with it within
# seconds; plain JVMs and loopback servers are unaffected).
#
# What this proves: every source file — including all Android glue —
# type-checks with zero errors against the exact dependency versions
# in app/build.gradle.kts. What it does NOT do: Compose compiler
# codegen (IR lowering needs the Compose plugin, which AGP applies
# in CI) and APK packaging. CI's build-debug job remains the
# packaging authority.
#
# Prerequisites (fetched during the money build, see PATCH_NOTES):
#   $PM_DEPS   directory of dependency .aar/.jar files + cp.txt
#              (colon-joined classpath of extracted classes.jars)
#   JDK 17, kotlinc 2.0.21, android-35 android.jar, org.json jar.
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TOOLS="${PM_TOOLS:-$HOME/workspace/tools}"
DEPS="${PM_DEPS:-/tmp/deps}"
export JAVA_HOME="${JAVA_HOME:-$(ls -d $TOOLS/jdk-17* | head -1)}"
CP=$(cat "$DEPS/cp.txt")
find "$ROOT/app/src/main/java" -name "*.kt" > /tmp/pm-sources.txt
# BuildConfig is generated by AGP; a stub stands in for the check.
mkdir -p /tmp/pm-stubs/com/hindsight/app
cat > /tmp/pm-stubs/com/hindsight/app/BuildConfig.kt <<'EOF'
package com.hindsight.app
object BuildConfig { const val VERSION_NAME: String = "0.2.0"; const val VERSION_CODE: Int = 5; const val APPLICATION_ID: String = "com.hindsight.app"; const val DEBUG: Boolean = true }
EOF
"$TOOLS/kotlinc/bin/kotlinc" \
  -cp "$CP:$TOOLS/android-sdk/platforms/android-35/android.jar:$TOOLS/jars/json-20240303.jar" \
  -d /tmp/pm-appclasses \
  $(cat /tmp/pm-sources.txt) /tmp/pm-stubs/com/hindsight/app/BuildConfig.kt
# kotlinc exits non-zero at IR lowering without the Compose plugin
# (CompositionLocal inlining); the type-check verdict is the error
# count from the frontend, so this script's caller inspects the log.
echo "type-check compile attempted; inspect output for 'error:' lines (frontend) vs IR-lowering exceptions (expected without the Compose plugin)"
